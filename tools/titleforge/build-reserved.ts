/**
 * build-reserved.ts — regenerate the real-title lists (`GeneratorSpec.reservedTitles`) for
 * title-composer and japanese-ln. A draw that reproduces one exactly is rejected and resampled
 * (`engine/generate.ts`, `RESERVED_RETRIES`).
 *
 *   npx tsx tools/titleforge/build-reserved.ts
 *
 * Sources per lexicon:
 *   - its frozen corpora, which its patterns and words were derived from, so they're the titles a
 *     draw is most likely to land on;
 *   - its pattern exemplars (real titles by definition; "(illustrative)" ones are skipped);
 *   - title-composer only: a short curated list of translated classics that its world-fiction
 *     shapes ("{abstractA} and {abstractB}", "{adjective} {subject}") can reach.
 * Each title is reserved as written, without bracketed tails, and as its main title before a
 * colon, since a draw never carries brackets and rarely a subtitle.
 *
 * webnovel's list has its own builder, tied to its hashed corpus
 * (`corpus-webnovel/v1.2.0/build-reserved.mjs`).
 */
