// @ts-nocheck
/**
 * build-reserved.mjs — regenerate `lexicons/westernSerialReserved.ts`, the collision guard's
 * list of real series names (brief Task 4). Run from anywhere:
 *   node src/titleforge/corpus-webnovel/v1.2.0/build-reserved.mjs
 *
 * Source, in order of preference:
 *   1. `webnovel.v1.2.0.json` (the frozen corpus) — every series `name`, but only when the file
 *      matches `webnovel.v1.2.0.sha256`. A hash mismatch is a hard error, never a silent fallback.
 *   2. `reserved-seed.json` — the lexicon's own source series, i.e. exactly the titles a slot
 *      filler can recombine into. A stopgap until the corpus is copied in; verify.mjs fails its
 *      hash check (and reports the source) while this is what ships.
 *
 * The seed is always merged in, so the guard never loses a name the lexicon was derived from.
 * Only names are bundled: the corpus's authors, sources and follower counts stay out of main.js.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const corpusPath = join(here, "webnovel.v1.2.0.json");
const hashPath = join(here, "webnovel.v1.2.0.sha256");
const out = join(here, "../../lexicons/westernSerialReserved.ts");

/** Every `name` on a series-shaped object, wherever the corpus nests its series array. */
function seriesNames(node, acc = []) {
	if (Array.isArray(node)) for (const n of node) seriesNames(n, acc);
	else if (node && typeof node === "object") {
		if (typeof node.name === "string") acc.push(node.name);
		else for (const v of Object.values(node)) seriesNames(v, acc);
	}
	return acc;
}

const names = new Set(JSON.parse(readFileSync(join(here, "reserved-seed.json"), "utf8")));
let source = "reserved-seed.json (lexicon source series only — frozen corpus not yet copied in)";
if (existsSync(corpusPath)) {
	const raw = readFileSync(corpusPath);
	const actual = createHash("sha256").update(raw).digest("hex");
	const expected = readFileSync(hashPath, "utf8").trim().split(/\s+/)[0];
	if (actual !== expected) throw new Error(`webnovel.v1.2.0.json hash ${actual} != ${expected}`);
	const corpusNames = seriesNames(JSON.parse(raw.toString("utf8")));
	if (corpusNames.length < 1000) throw new Error(`only ${corpusNames.length} names found — corpus shape changed?`);
	for (const n of corpusNames) {
		names.add(n.trim());
		// Some names keep a normaliser leftover ("Amber the Cursed Berserker ()", "... (Completed)").
		// Generated names never contain brackets, so also reserve the bracket-free form, or the
		// guard could never match them.
		const cleaned = n.replace(/\s*[([][^)\]]*[)\]]\s*/g, " ").replace(/\s+/g, " ").trim();
		if (cleaned) names.add(cleaned);
	}
	source = `webnovel.v1.2.0.json sha256 ${actual}`;
}

const sorted = [...names].filter(Boolean).sort((a, b) => a.localeCompare(b));
writeFileSync(
	out,
	`// GENERATED by corpus-webnovel/v1.2.0/build-reserved.mjs — do not edit by hand.
// Source: ${source}

/** Real series names the webnovel generator must never reproduce (\`GeneratorSpec.reservedTitles\`). */
export const WESTERN_SERIAL_RESERVED_SOURCE = ${JSON.stringify(source)};

export const westernSerialReservedTitles: readonly string[] = ${JSON.stringify(sorted, null, "\t")};
`,
);
console.log(`${sorted.length} reserved titles from ${source}`);
